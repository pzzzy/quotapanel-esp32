"""Build the ESP32 PEM trust store from pinned Mozilla/certifi roots.
Full certificates support mbedTLS path selection for cross-signed chains.
No machine trust store or downloaded leaf/intermediate certificate is imported.
"""

import argparse
import hashlib
import importlib.metadata
import json
from pathlib import Path

import certifi
from cryptography import x509
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

ROOT = Path(__file__).resolve().parents[1]


def build_bundle(pem):
    roots = x509.load_pem_x509_certificates(pem)
    entries = {}
    for cert in roots:
        subject = cert.subject.public_bytes()
        key = cert.public_key().public_bytes(
            Encoding.DER, PublicFormat.SubjectPublicKeyInfo
        )
        if subject in entries and entries[subject][0] != key:
            raise ValueError("Conflicting root keys with the same subject")
        entries[subject] = (key, cert.public_bytes(Encoding.PEM))
    # Preserve full certificates so mbedTLS can select a trusted path through
    # cross-signed chains. Strip comments only; don't change the trust set.
    bundle = b"".join(cert for _, (_, cert) in sorted(entries.items()))
    return bundle, roots


def outputs():
    pem = Path(certifi.where()).read_bytes()
    bundle, roots = build_bundle(pem)
    header = [
        "// Mozilla/certifi root data: MPL-2.0; see licenses/Certifi-MPL-2.0.txt.",
        "// Generated by tools/generate_ca_bundle.py. Do not hand-edit.",
        "#pragma once",
        'static const char NATIVE_ROOTS[] PROGMEM = R"PEM('
        + bundle.decode("ascii")
        + ')PEM";',
    ]
    meta = {
        "source": "Mozilla root store via certifi",
        "certifiVersion": importlib.metadata.version("certifi"),
        "pemSha256": hashlib.sha256(pem).hexdigest(),
        "bundleSha256": hashlib.sha256(bundle).hexdigest(),
        "certificateCount": len(roots),
        "format": "PEM certificates, comments removed",
        "bundleBytes": len(bundle),
        "subjects": sorted(c.subject.rfc4514_string() for c in roots),
    }
    return {
        ROOT / "assets/ca-roots.pem": pem.decode("ascii"),
        ROOT / "firmware/src/native_roots.h": "\n".join(header) + "\n",
        ROOT / "assets/ca-bundle.json": json.dumps(meta, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Outdated CA bundle: regenerate {path.name}")
        else:
            path.write_text(expected)
    print("CA bundle verified." if args.check else "CA bundle generated.")


if __name__ == "__main__":
    main()
