#include "codec_es8311.h"
#include <Arduino.h>
#include <Wire.h>
namespace {
bool write(uint8_t reg,uint8_t value){
    Wire.beginTransmission(0x18);
    return Wire.write(reg)==1 && Wire.write(value)==1 && Wire.endTransmission()==0;
}
bool matches(uint8_t reg,uint8_t mask,uint8_t expected){
    Wire.beginTransmission(0x18);
    if(Wire.write(reg)!=1||Wire.endTransmission(false)!=0||Wire.requestFrom(0x18,1)!=1)return false;
    int value=Wire.read();return value>=0&&((uint8_t)value&mask)==expected;
}
}
bool codecEs8311Begin(){
    Wire.setTimeOut(50);
    // The first codec write can fail during power-up; upstream retries GPIO44.
    write(0x44,0x08);if(!write(0x44,0x08))return false;
    // 22,050 Hz, MCLK = 256 Fs, slave, normal 16-bit stereo I2S.
    // ADC data output stays disabled; no microphone/I2S input is configured.
    const uint8_t setup[][2]={
        {0x0d,0xfa},{0x01,0x30},{0x02,0x00},{0x03,0x10},{0x16,0x24},
        {0x04,0x10},{0x05,0x00},{0x0b,0x00},{0x0c,0x00},{0x10,0x1f},
        {0x11,0x7f},{0x00,0x80},{0x01,0x3f},{0x06,0x03},{0x07,0x00},
        {0x08,0xff},{0x13,0x10},{0x1b,0x0a},{0x1c,0x6a},{0x44,0x08},
        {0x09,0x0c},{0x0a,0x4c},{0x17,0xbf},{0x0e,0x02},{0x12,0x00},
        {0x14,0x1a},{0x0d,0x01},{0x15,0x40},{0x37,0x08},{0x45,0x00},
        {0x31,0x00},{0x32,0xbf}
    };
    for(auto &pair:setup)if(!write(pair[0],pair[1]))return false;
    return matches(0x00,0x40,0x00)&&matches(0x01,0xff,0x3f)&&
        matches(0x02,0xf8,0x00)&&matches(0x03,0x7f,0x10)&&matches(0x04,0x7f,0x10)&&
        matches(0x05,0xff,0x00)&&matches(0x06,0x3f,0x03)&&matches(0x07,0x3f,0x00)&&
        matches(0x08,0xff,0xff)&&matches(0x09,0x7f,0x0c)&&matches(0x31,0x60,0x00)&&matches(0x32,0xff,0xbf);
}
